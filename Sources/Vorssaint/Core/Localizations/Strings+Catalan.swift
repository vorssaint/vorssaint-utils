// Sources, in order: macOS's own Catalan for anything macOS names, then the choices
// below, then Optimot, the IEC grammars and TERMCAT, then the Softcatalà style guide.
// For natural wording, Jordi Badia and Pau Vidal: prefer what Catalan already says over
// a calque of the English. Translate from the current English, not from another language.
// macOS's strings are in the `.loctable` files inside its system bundles.
//
// Deliberate choices, so please don't "correct" them:
// - Address the user as tu everywhere: "Vols eliminar…?". Never vós or vostè.
// - "app" and "arxiu", as macOS writes them, not "aplicació" and "fitxer".
// - "descàrrega" and "pujada", not "baixada".
// - Progress uses a personal verb form, "S’està desant…", against macOS's usual bare gerund.
// - An article before apps and brands: el Vorssaint, el Finder, el Claude. Not before %@.
// - notch is "osca", introduced once as "osca (notch)" in iconMissingCaption.
// - An AI token is "segment" (TERMCAT). An authentication token is "testimoni".
//
// Verb forms:
// - Buttons and commands: imperative. "Desa", "Obre", "Surt del Vorssaint". No infinitives.
// - Toggles: imperative for an action, "Mostra a la barra de menús"; a noun for a state.
// - Titles of pages and sections: a noun, never a gerund. "Captura de pantalla".
// - Function names with no natural noun keep the infinitive and take quotes when
//   mentioned: "Activa “Mantenir actiu”".
// - Descriptions: third person or a noun phrase. Negatives: "No permetis".
// - Errors: a full sentence, "No s’ha pogut desar l’arxiu.", never "Error en desar".
//
// English habits to avoid:
// - Gerunds of consequence or specification: "que indica…", not "indicant".
// - Estar + gerund outside progress states: "El servidor no respon".
// - Possessives the context makes clear: "Desa els canvis", not "els teus canvis".
// - Periphrastic passive: "S’ha desat", not "ha estat desat".
// - "el mateix" as a pronoun, "a nivell de", "en base a", and an added "si us plau".
// Add the articles English leaves out, use weak pronouns ("Torna-ho a provar"), and agree
// in the masculine without double forms. Rephrase rather than guess a placeholder's
// gender: "Arxiu: %@".
//
// Typography: apostrophe ’, ellipsis …, quotes “ ”. No em dashes. A non-breaking space
// before %, "%d %%", and a space before units, "5 min". Capitalize only the first word,
// plus proper nouns and macOS names. Keep every placeholder, `\( )` and `\n` intact.
//
// Space, measured in the app:
// - Settings sidebar: about 21 characters before "…".
// - Feature descriptions on the onboarding screen: about 145 characters.
// - Feature names double as page titles, so check that a short name still works there.
// Tests also expect sourceClipboard to differ from the Clipboard page title.
//
// Terms:
// System Settings: "l’app Configuració del Sistema" in a sentence, "Obre la configuració
//   del sistema" as a button. Menu bar: barra de menús. Control Center: Centre de control.
// Stage Manager: Organitzador visual. Hot Corners: Angles actius. Login Items: Ítems d’inici
//   de sessió. Clipboard: porta-retalls. Screen Recording: gravació de pantalla. Sleep: repòs.
// Trash: paperera. Move to Trash: Trasllada a la paperera. Default: per omissió. Item: ítem.
// About: Informació as a page, “Sobre el Vorssaint” in the app menu. Rename: Canvia el nom. Reset: Restableix. Remove, Delete: Elimina. Clear, Erase: Esborra.
// Keys: Ordre, Opció, Control, Majúscules, Retorn, Esc, Espai, Fn, Supressió.
// Mission Control, Spotlight, Dock, Finder and AirDrop stay as they are. A desktop Space
//   stays too, masculine as in macOS: "un Space", "els Spaces". "Espai" is only for room.
// Dynamic Island: la Dynamic Island, feminine. Keep Awake: Mantenir actiu. Shelf: prestatge.
// Scratchpad: bloc de notes. Snippet: fragment. Cleaner: Netejador. Mixer: mesclador de volum.
// Switcher: selector. Super Key: supertecla. Command Bar: barra d’ordres. Panel: tauler.
// Hover: passar el punter. Swipe: fer lliscar. Pinch: pinçar. Prompt (AI): instrucció.
