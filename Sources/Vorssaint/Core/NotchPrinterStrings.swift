struct NotchPrinterStrings {
    let title: String
    let summary: String
    let description: String
    let setupHint: String
    let notConfigured: String
    let connecting: String
    let unreachable: String
    let idle: String
    let preparing: String
    let printing: String
    let paused: String
    let finished: String
    let failed: String
    let nozzle: String
    let bed: String
    let layerFormat: String
    let leftFormat: String
    let finishedNotice: String
    let failedNotice: String
    let pausedNotice: String
    let openSettings: String
    let connected: String
    let email: String
    let password: String
    let signIn: String
    let code: String
    let verify: String
    let resend: String
    let cancel: String
    let emailCodePrompt: String
    let twoFactorPrompt: String
    let signedInFormat: String
    let signOut: String
    let printer: String
    let noPrinters: String
    let refresh: String
    let signInFailed: String
    let signInAgain: String
    let cloudHint: String
    let layerTitle: String

    func state(_ state: PrinterJobState) -> String {
        switch state {
        case .preparing: return preparing
        case .printing: return printing
        case .paused: return paused
        case .finished: return finished
        case .failed: return failed
        case .idle, .unknown: return idle
        }
    }

    func layer(_ layer: Int, of total: Int) -> String { String(format: layerFormat, layer, total) }
    func left(_ time: String) -> String { String(format: leftFormat, time) }
    func signedIn(_ email: String) -> String { String(format: signedInFormat, email) }
}

