    let pageTitle: String
    let hubDescription: String
    let openButton: String
    let caption: String
    let editHint: String
    let search: String
    let noResults: String
    let styleTitle: String
    let styleFullScreen: String
    let stylePanel: String
    let dockTitle: String
    let addToDock: String
    let dockCaption: String
    let dockAdded: String
    let dockFailed: String
    let categories: String
    let newFolder: String
    let folderName: String
    let untitledFolder: String
    let searchApps: String
    let done: String
    let cancel: String
    let open: String
    let showInFinder: String
    let hideApp: String
    let unhideApp: String
    let removeFromFolder: String
    let editFolder: String
    let deleteFolder: String
    let moveToTrash: String
    let deleteTitleFormat: String
    let deleteMessage: String
    let deleteFailedFormat: String
    let resetLayout: String
    let resetLayoutMessage: String
    let productivity: String
    let utilities: String
    let developer: String
    let graphics: String
    let photoVideo: String
    let music: String
    let games: String
    let social: String
    let reading: String
    let other: String
    let hidden: String

    func title(_ category: LaunchpadCategory) -> String {
        switch category {
        case .productivity: return productivity
        case .utilities: return utilities
        case .developer: return developer
        case .graphics: return graphics
        case .photoVideo: return photoVideo
        case .music: return music
        case .games: return games
        case .social: return social
        case .reading: return reading
        case .other: return other
        case .hidden: return hidden
        }
    }

    func title(_ style: LaunchpadSupport.Style) -> String {
        switch style {
        case .fullScreen: return styleFullScreen
        case .panel: return stylePanel
        }
    }
}

extension FeatureStrings {
    static func launchpad(_ language: AppLanguage) -> LaunchpadFeatureStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ja: return .ja
        case .ko: return .ko
        case .uk: return .uk
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        }
    }
}

