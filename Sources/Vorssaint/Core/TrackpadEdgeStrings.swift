    let sensitivityGentle: String
    let sensitivityNormal: String
    let sensitivityFast: String
    let preciseToggle: String
    let preciseCaption: String
    let hapticsToggle: String
    let hapticsCaption: String
    let freezeCursorToggle: String
    let freezeCursorCaption: String
    let modifierLabel: String
    let modifierNone: String
    let modifierFn: String
    let modifierOption: String
    let modifierCaption: String
    let feedbackNote: String
    let microphoneLevelFormat: String
    let microphoneMutedNotice: String

    func name(_ edge: TrackpadEdge) -> String {
        switch edge {
        case .left: return edgeLeft
        case .right: return edgeRight
        case .top: return edgeTop
        case .bottom: return edgeBottom
        }
    }

    func name(_ corner: TrackpadCorner) -> String {
        switch corner {
        case .topLeft: return cornerTopLeft
        case .topRight: return cornerTopRight
        case .bottomLeft: return cornerBottomLeft
        case .bottomRight: return cornerBottomRight
        }
    }

    func name(_ action: TrackpadSlideAction) -> String {
        switch action {
        case .off: return slideOff
        case .volume: return slideVolume
        case .brightness: return slideBrightness
        case .keyboardBrightness: return slideKeyboardBrightness
        case .microphoneVolume: return slideMicrophoneVolume
        case .tracks: return slideTracks
        }
    }

    func name(_ action: TrackpadCornerAction) -> String {
        switch action {
        case .off: return slideOff
        case .microphoneMute: return tapMicrophoneMute
        case .outputMute: return tapOutputMute
        case .playPause: return tapPlayPause
        case .nextTrack: return tapNextTrack
        case .previousTrack: return tapPreviousTrack
        case .missionControl: return tapMissionControl
        case .appExpose: return tapAppExpose
        case .nextSoundOutput: return tapNextSoundOutput
        case .lockScreen: return tapLockScreen
        }
    }

    func name(_ area: TrackpadActiveArea) -> String {
        switch area {
        case .full: return activeFull
        case .threeQuarters: return activeThreeQuarters
        case .half: return activeHalf
        case .quarter: return activeQuarter
        }
    }

    func name(_ sensitivity: TrackpadSlideSensitivity) -> String {
        switch sensitivity {
        case .gentle: return sensitivityGentle
        case .normal: return sensitivityNormal
        case .fast: return sensitivityFast
        }
    }

    func name(_ modifier: TrackpadEdgeModifier) -> String {
        switch modifier {
        case .none: return modifierNone
        case .fn: return modifierFn
        case .option: return modifierOption
        }
    }

    func microphoneLevel(_ level: Double) -> String {
        String(format: microphoneLevelFormat, Int((min(max(level, 0), 1) * 100).rounded()))
    }
}

