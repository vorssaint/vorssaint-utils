import Foundation

/// The lock screen widgets' own words: the rings, the battery, the AI rail
/// and the streak.
struct NotchLockScreenWidgetStrings {
    /// Under a ring: how much is in use.
    let inUse: String
    /// Under a ring: a chip's temperature.
    let temp: String
    /// Under memory's second ring.
    let pressure: String
    let pressureLow: String
    let pressureMedium: String
    let pressureHigh: String
    /// Under the network's rings.
    let down: String
    let up: String
    /// "Peak 61%", the highest the history holds.
    let peakFormat: String
    /// How far back the GPU's history reaches.
    let lastMinutesFormat: String
    /// "12-core", beside CPU and GPU.
    let coresFormat: String
    let compressedFormat: String
    let swapFormat: String
    /// The kind of connection, never its name.
    let wifi: String
    let ethernet: String
    /// Traffic since the app started watching.
    let totalFormat: String
    /// "Fans 1,850 RPM".
    let fansFormat: String
    /// Accessories with a battery reading.
    let connectedFormat: String
    /// An accessory by its kind, never its Bluetooth name.
    let keyboard: String
    let mouse: String
    let trackpad: String
    let headphones: String
    let device: String
    /// Under the battery's time left.
    let leftAtRate: String
    /// The power the Mac draws on battery.
    let using: String
    let cyclesFormat: String
    /// When Keep Awake ends.
    let awakeUntil: String
    /// Today's events still to come.
    let leftFormat: String
    let lifetime: String
    /// Under the lifetime total with amounts hidden.
    let tokensAllTime: String
    let agentsAtWork: String
    let runningFormat: String
    let allQuiet: String
    let noneRunning: String
    /// After No sessions running, with a time.
    let lastEndedFormat: String
    /// Where a session runs.
    let terminal: String
    /// "Claude app", with the agent's name.
    let appFormat: String
    let streak: String
    /// Under the streak's count.
    let daysInARow: String
    /// "Best 21 days".
    let bestFormat: String
    /// Under the streak's bars.
    let hoverHint: String
    /// The streak's tooltip.
    let spent: String
    let tokens: String
    let inOutFormat: String
    let requests: String
    let topModel: String
    let noUse: String
}

extension FeatureStrings {
    static func notchLockScreenWidgets(_ language: AppLanguage) -> NotchLockScreenWidgetStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ru: return .ru
        case .tr: return .tr
        case .ja: return .ja
        case .ko: return .ko
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        case .uk: return .uk
        }
    }
}

