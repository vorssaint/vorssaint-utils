    static func text(_ key: Key, _ language: AppLanguage = L10n.shared.language,
                     ai: String = "", cmd: String = "", said: String = "", reason: String = "") -> String {
        values(language)[key.rawValue]
            .replacingOccurrences(of: "{ai}", with: ai)
            .replacingOccurrences(of: "{cmd}", with: cmd)
            .replacingOccurrences(of: "{said}", with: said)
            .replacingOccurrences(of: "{reason}", with: reason)
    }
