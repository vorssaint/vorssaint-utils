#!/usr/bin/env python3
"""Writes Sources/Vorssaint/Services/Notch/AgentDotAnimationData.swift from the
JSON files beside this script. Run after `node generate.js`:
    python3 Tools/agent-animations/export-swift.py
The thinking order follows README.md's table."""
import json, re
from pathlib import Path

here = Path(__file__).resolve().parent
root = here.parents[1]
order = re.findall(r"`thinking-([a-z]+)\.json`", (here / "README.md").read_text())

def load(name):
    data = json.loads((here / name).read_text())
    cols, rows = data["grid"]
    for frame in data["frames"]:
        assert len(frame) == rows and all(len(r) == cols and set(r) <= set("012") for r in frame), name
    assert 0 <= data["still"] < len(data["frames"]), name
    return data

def swift(id_, data):
    frames = ",\n".join('            [' + ", ".join(f'"{r}"' for r in f) + ']' for f in data["frames"])
    return (f'    static let {id_} = AgentDotAnimation(\n'
            f'        id: "{id_}", fps: {data["fps"]}, loops: {"true" if data["loop"] else "false"}, still: {data["still"]},\n'
            f'        frames: [\n{frames}\n        ])\n')

parts = [swift(n, load(f"thinking-{n}.json")) for n in order]
parts.append(swift("question", load("question.json")))
parts.append(swift("done", load("done.json")))
out = ("// SPDX-License-Identifier: GPL-3.0-or-later\n// Copyright (C) 2026 Vorssaint\n\n"
       "// Generated by Tools/agent-animations/export-swift.py from the JSON files\n"
       "// there. Edit those (or generate.js) and run the script again.\n\n"
       "extension AgentDotAnimation {\n"
       f"    /// The thinking choices, in the order the settings list them.\n"
       f"    static let thinking: [AgentDotAnimation] = [{', '.join(order)}]\n\n"
       + "\n".join(parts) + "}\n")
target = root / "Sources/Vorssaint/Services/Notch/AgentDotAnimationData.swift"
target.write_text(out)
print(f"wrote {target.relative_to(root)}: {len(order)} thinking + question + done")
